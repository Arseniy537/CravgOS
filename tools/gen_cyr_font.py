for i,ch in enumerate("рстуфхцчшщъыьэюя"): CODES[ch]=0xE0+i
for ch,c in zip("ЁёЄєЇїЎў",range(0xF0,0xF8)): CODES[ch]=c
def bitmap(top, rows):
    cell=[0]*16
    for i,r in enumerate(rows):
        y=top+i
        assert 0<=y<16, (r, top, i)
        assert len(r)<=8 and set(r)<=set('#.'), r
        v=0
        for x,c in enumerate(r):
            if c=='#': v|=0x80>>x
        cell[y]=v
    return cell
def build():
    out={}
    for d in (U,L):
        for ch,(top,rows) in d.items(): out[CODES[ch]]=(ch,bitmap(top,rows))
    return out
